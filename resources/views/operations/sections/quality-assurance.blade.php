<h4>Risk Control Measures</h4>
<ul>
    <li><strong>Risk Elimination:</strong> Remove the hazard completely when possible</li>
    <li><strong>Risk Reduction:</strong> Implement controls to reduce probability or severity</li>
    <li><strong>Risk Segregation:</strong> Isolate the risk from operations</li>
    <li><strong>Risk Transfer:</strong> Share or transfer risk to third parties</li>
    <li><strong>Risk Acceptance:</strong> Accept residual risk with appropriate monitoring</li>
</ul>

