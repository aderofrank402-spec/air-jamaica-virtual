<h2>Flight Operations Quality Assurance</h2>

<h3>Flight Data Monitoring</h3>

<div class="success-box">
    <div class="box-title">
        <i class="fas fa-chart-line"></i>
        FOQA Program
    </div>
    <p>Our Flight Operations Quality Assurance program continuously monitors flight operations to identify trends and enhance safety.</p>
</div>

<h4>Monitored Parameters</h4>
<ul>
    <li><strong>Takeoff Performance:</strong> V-speeds, rotation rate, climb gradient</li>
    <li><strong>En-route Operations:</strong> Altitude deviations, speed variations, fuel consumption</li>
    <li><strong>Approach Monitoring:</strong> Stabilized approach criteria, glidepath tracking</li>
    <li><strong>Landing Performance:</strong> Touchdown point, sink rate, runway usage</li>
    <li><strong>System Usage:</strong> Autopilot engagement, navigation accuracy</li>
</ul>

