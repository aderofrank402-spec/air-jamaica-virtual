<h2>Code of Conduct</h2>

<div class="warning-box">
    <div class="box-title">
        <i class="fas fa-exclamation-triangle"></i>
        Professional Standards
    </div>
    <p>All Air Jamaica Virtual members are expected to maintain the highest standards of professional conduct in all airline-related activities.</p>
</div>

<h3>Expected Behavior</h3>
<ul>
    <li>Treat all members with respect and courtesy</li>
    <li>Follow all operational procedures and guidelines</li>
    <li>Maintain punctuality for scheduled events and flights</li>
    <li>Provide constructive feedback and support to fellow pilots</li>
    <li>Report any safety concerns or violations promptly</li>
    <li>Participate actively in airline community activities</li>
</ul>

<h3>Prohibited Conduct</h3>
<ul>
    <li>Harassment, discrimination, or inappropriate behavior</li>
    <li>Violation of flight procedures or safety protocols</li>
    <li>Sharing confidential airline information</li>
    <li>Representing the airline without authorization</li>
    <li>Disruptive behavior during events or training</li>
    <li>Intentional system abuse or exploitation</li>
</ul>

