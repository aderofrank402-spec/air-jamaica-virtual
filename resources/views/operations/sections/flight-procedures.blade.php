<h3>Weight and Balance</h3>
<p>Ensure proper weight and balance calculations for all flights:</p>
<ol>
    <li>Verify aircraft empty weight and center of gravity</li>
    <li>Calculate passenger and cargo distribution</li>
    <li>Confirm fuel loading and distribution</li>
    <li>Verify total weight within aircraft limits</li>
    <li>Confirm center of gravity within acceptable range</li>
</ol>

<h2>Pre-Flight Procedures</h2>

<h3>Aircraft Inspection</h3>
<div class="warning-box">
    <div class="box-title">
        <i class="fas fa-search"></i>
        Pre-Flight Inspection
    </div>
    <p>A thorough pre-flight inspection must be completed before every flight, following the aircraft-specific checklist.</p>
</div>

<h4>External Inspection</h4>
<ul>
    <li>Fuselage condition and structural integrity</li>
    <li>Wing surfaces, control surfaces, and attachments</li>
    <li>Landing gear condition and tire wear</li>
    <li>Engine nacelles and intakes</li>
    <li>Pitot tubes, static ports, and antennas</li>
    <li>Navigation and strobe lights functionality</li>
</ul>

<h4>Internal Inspection</h4>
<ul>
    <li>Cockpit security and cleanliness</li>
    <li>Emergency equipment accessibility</li>
    <li>Cabin configuration and safety equipment</li>
    <li>Cargo compartment security</li>
    <li>Documentation and charts current</li>
</ul>

<h3>Flight Management System Setup</h3>
<p>Proper FMS programming is critical for navigation accuracy:</p>
<ol>
    <li>Enter departure airport and runway</li>
    <li>Program complete route including waypoints</li>
    <li>Verify arrival airport and approach</li>
    <li>Enter performance data (weights, cost index)</li>
    <li>Review and cross-check all entries</li>
    <li>Brief the planned route and alternates</li>
</ol>

