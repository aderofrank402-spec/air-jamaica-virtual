<h3>Takeoff Performance</h3>
<p>Calculate and verify takeoff performance data:</p>
<ul>
    <li><strong>V1:</strong> Decision speed for continued takeoff</li>
    <li><strong>VR:</strong> Rotation speed for liftoff</li>
    <li><strong>V2:</strong> Takeoff safety speed</li>
    <li><strong>Runway Length:</strong> Verify adequate distance available</li>
    <li><strong>Weight Limits:</strong> Confirm within maximum takeoff weight</li>
</ul>

<h2>En Route Procedures</h2>

<h3>Climb Procedures</h3>
<div class="info-box">
    <div class="box-title">
        <i class="fas fa-arrow-up"></i>
        Standard Climb Profile
    </div>
    <p>Follow standard climb procedures to ensure efficiency and ATC compliance.</p>
</div>

<ol>
    <li>Maintain V2 until safe altitude (minimum 400 feet AGL)</li>
    <li>Accelerate to climb speed as appropriate</li>
    <li>Follow SID procedures or ATC instructions</li>
    <li>Monitor engine parameters continuously</li>
    <li>Complete after-takeoff checklist</li>
    <li>Request higher altitude when appropriate</li>
</ol>

<h3>Cruise Operations</h3>
<h4>Level-off Procedures</h4>
<ul>
    <li>Begin level-off approximately 1000 feet before target altitude</li>
    <li>Reduce vertical speed gradually to maintain smooth flight</li>
    <li>Adjust power to maintain desired airspeed</li>
    <li>Trim aircraft for hands-off flight</li>
    <li>Monitor fuel consumption and flight progress</li>
</ul>

<h4>Navigation Monitoring</h4>
<p>Continuous navigation monitoring is required throughout the flight:</p>
<ul>
    <li>Cross-check navigation displays every 15 minutes</li>
    <li>Verify waypoint passage and estimated times</li>
    <li>Monitor fuel consumption against flight plan</li>
    <li>Update weather information as available</li>
    <li>Maintain situational awareness of alternate airports</li>
</ul>

<h3>Communications</h3>
<div class="success-box">
    <div class="box-title">
        <i class="fas fa-radio"></i>
        Communication Standards
    </div>
    <p>Professional communication with ATC and other aircraft is essential for safe operations.</p>
