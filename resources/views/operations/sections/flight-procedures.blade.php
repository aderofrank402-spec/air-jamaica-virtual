<h3>Stabilized Approach Criteria</h3>
<div class="warning-box">
    <div class="box-title">
        <i class="fas fa-exclamation-triangle"></i>
        Go-Around Decision
    </div>
    <p>Execute a go-around if the approach is not stabilized by 1000 feet AGL (500 feet for visual approaches).</p>
</div>

<h4>Stabilized Approach Requirements</h4>
<ul>
    <li>Aircraft on correct flight path</li>
    <li>Proper airspeed (Vref + 5 to + 15 knots)</li>
    <li>Correct aircraft configuration</li>
    <li>Descent rate not exceeding 1000 fpm</li>
    <li>Power setting appropriate for configuration</li>
    <li>All checklists completed</li>
</ul>

<h3>Landing Technique</h3>
<ol>
    <li>Maintain approach speed until reaching flare altitude</li>
    <li>Begin flare at appropriate height (30-50 feet AGL)</li>
    <li>Gradually reduce power to idle</li>
    <li>Maintain directional control with rudder</li>
    <li>Touch down on main landing gear first</li>
    <li>Apply wheel brakes and reverse thrust as appropriate</li>
</ol>

<h2>Post-Flight Procedures</h2>

<h3>After Landing</h3>
<div class="code-block">
After Landing Checklist:
1. Speed brakes - DEPLOYED
2. Reverse thrust - AS REQUIRED
3. Autobrakes - AS SET
4. Transponder - STANDBY
5. Flaps - UP (when clear of runway)
6. APU - START (if required)
</div>

<h3>Shutdown Procedures</h3>
<ul>
    <li>Position aircraft at designated parking area</li>
    <li>Set parking brake and chocks</li>
    <li>Shutdown engines following proper sequence</li>
    <li>Complete shutdown checklist</li>
    <li>Secure aircraft and remove personal items</li>
    <li>Complete flight log and maintenance entries</li>
</ul>

<h3>Flight Report Submission</h3>
<p>Submit complete flight report within 2 hours of flight completion:</p>
<ul>
    <li>Flight time and fuel consumption</li>
    <li>Route flown and any deviations</li>
    <li>Weather encountered</li>
    <li>Aircraft performance notes</li>
    <li>Any maintenance discrepancies</li>
    <li>Passenger and cargo information</li>
</ul>