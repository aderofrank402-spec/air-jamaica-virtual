<h5>Pressurization Emergency</h5>
<div class="danger-box">
    <div class="box-title">
        <i class="fas fa-mask"></i>
        Rapid Decompression
    </div>
    <p>Rapid decompression requires immediate crew action to ensure safety and initiate emergency descent.</p>
</div>

<p><strong>Immediate Actions:</strong></p>
<ol>
    <li>Don oxygen masks immediately</li>
    <li>Establish crew communications</li>
    <li>Begin emergency descent to 10,000 feet or MEA</li>
    <li>Declare emergency with ATC</li>
    <li>Monitor cabin altitude and crew/passenger status</li>
    <li>Plan diversion to nearest suitable airport</li>
</ol>

<h5>Fire Emergency</h5>
<p><strong>Engine Fire:</strong></p>
<ul>
    <li>Engine fire switch - PULL</li>
    <li>Engine fuel lever - CUTOFF</li>
    <li>Generator - OFF</li>
    <li>Fire suppression - ACTIVATE if fire persists</li>
    <li>Land at nearest suitable airport</li>
</ul>

<p><strong>Cabin Fire:</strong></p>
<ul>
    <li>Identify source and type of fire</li>
    <li>Use appropriate fire suppression equipment</li>
    <li>Isolate electrical systems if electrical fire</li>
    <li>Consider emergency descent if necessary</li>
    <li>Plan immediate landing</li>
</ul>

<h3>Ground Emergency Procedures</h3>

<h4>Aircraft Ground Emergencies</h4>

<h5>Ground Fire</h5>
<div class="warning-box">
    <div class="box-title">
        <i class="fas fa-fire"></i>
        Ground Fire Response
    </div>
    <p>Ground fires require immediate action to protect personnel and aircraft.</p>
</div>

<p><strong>Pilot Actions:</strong></p>
<ol>
    <li>Engine/APU fire switches - PULL as required</li>
    <li>Fuel shutoff valves - CLOSED</li>
    <li>Electrical power - OFF</li>
    <li>Evacuate aircraft if necessary</li>
    <li>Notify ground control and emergency services</li>
</ol>

<h5>Ground Collision</h5>
<p><strong>Response Procedures:</strong></p>
<ul>
    <li>Stop aircraft movement immediately</li>
    <li>Secure aircraft systems</li>
    <li>Assess damage and personnel status</li>
    <li>Notify ground control and operations</li>
    <li>Request emergency services if needed</li>
    <li>Document incident thoroughly</li>
</ul>

