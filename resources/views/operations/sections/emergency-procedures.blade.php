<h3>Emergency Classifications</h3>

<h4>Level 1 - Minor Emergency</h4>
<div class="warning-box">
    <div class="box-title">
        <i class="fas fa-info-circle"></i>
        Level 1 Characteristics
    </div>
    <p>Localized incidents with minimal impact on operations and no immediate safety concerns.</p>
</div>

<ul>
    <li><strong>Examples:</strong> Single pilot issues, minor system glitches, training disruptions</li>
    <li><strong>Response Time:</strong> Within 2 hours</li>
    <li><strong>Authority Level:</strong> Department head can manage independently</li>
    <li><strong>Communication:</strong> Internal notification only</li>
    <li><strong>Documentation:</strong> Incident report required</li>
</ul>

<h4>Level 2 - Major Emergency</h4>
<div class="warning-box">
    <div class="box-title">
        <i class="fas fa-exclamation-triangle"></i>
        Level 2 Characteristics
    </div>
    <p>Significant incidents affecting multiple operations or requiring coordinated response.</p>
</div>

<ul>
    <li><strong>Examples:</strong> System-wide outages, multiple pilot incidents, major training issues</li>
    <li><strong>Response Time:</strong> Within 1 hour</li>
    <li><strong>Authority Level:</strong> Senior management involvement required</li>
    <li><strong>Communication:</strong> All staff notification</li>
    <li><strong>Documentation:</strong> Comprehensive incident investigation</li>
</ul>

<h4>Level 3 - Critical Emergency</h4>
<div class="danger-box">
    <div class="box-title">
        <i class="fas fa-times-circle"></i>
        Level 3 Characteristics
    </div>
    <p>Severe incidents with potential for significant operational impact or safety concerns.</p>
</div>

<ul>
    <li><strong>Examples:</strong> Complete system failures, security breaches, serious safety incidents</li>
    <li><strong>Response Time:</strong> Immediate (within 30 minutes)</li>
    <li><strong>Authority Level:</strong> Executive team activation</li>
    <li><strong>Communication:</strong> External notification may be required</li>
    <li><strong>Documentation:</strong> Full emergency response review and analysis</li>
</ul>

