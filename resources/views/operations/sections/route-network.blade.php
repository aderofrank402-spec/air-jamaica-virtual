<h4>Planning Considerations</h4>
<ol>
    <li><strong>Aircraft Performance:</strong> Verify aircraft capability for route requirements</li>
    <li><strong>Fuel Requirements:</strong> Calculate fuel needs including reserves and alternates</li>
    <li><strong>Weather Analysis:</strong> Review current and forecast conditions</li>
    <li><strong>NOTAM Review:</strong> Check for airspace restrictions and airport conditions</li>
    <li><strong>Alternate Selection:</strong> Identify suitable alternate airports</li>
    <li><strong>ETOPS Considerations:</strong> For extended overwater operations</li>
