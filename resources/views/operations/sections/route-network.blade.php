    <li><strong>Route Planning:</strong> Identify suitable diversion airports</li>
    <li><strong>Weather Monitoring:</strong> Continuous monitoring of diversion airports</li>
    <li><strong>Fuel Planning:</strong> Additional fuel for diversion scenarios</li>
</ul>

<h3>Volcanic Ash Procedures</h3>
<p>Caribbean operations require awareness of volcanic activity:</p>

<h4>Monitoring Requirements</h4>
<ol>
    <li>Check Volcanic Ash Advisory Centers (VAAC) reports</li>
    <li>Monitor pilot reports of volcanic ash encounters</li>
    <li>Review satellite imagery for ash clouds</li>
    <li>Coordinate with dispatch for route changes if necessary</li>
    <li>Consider fuel penalties for route deviations</li>
</ol>

<h3>Hurricane Season Operations</h3>
<div class="warning-box">
    <div class="box-title">
        <i class="fas fa-hurricane"></i>
        Seasonal Considerations
    </div>
    <p>June through November requires enhanced weather monitoring and contingency planning for hurricane activity.</p>
</div>

<h4>Hurricane Response Procedures</h4>
<ul>
    <li><strong>72 Hours Out:</strong> Begin enhanced monitoring and planning</li>
    <li><strong>48 Hours Out:</strong> Consider schedule adjustments and cancellations</li>
    <li><strong>24 Hours Out:</strong> Implement contingency plans and crew positioning</li>
    <li><strong>12 Hours Out:</strong> Final go/no-go decisions for affected routes</li>
    <li><strong>Post-Storm:</strong> Airport condition verification before resumption</li>
</ul>

