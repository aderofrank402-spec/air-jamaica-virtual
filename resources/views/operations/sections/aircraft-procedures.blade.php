<h2>Type Rating Requirements</h2>

<h3>Training Prerequisites</h3>
<p>Before operating any aircraft in the Air Jamaica Virtual fleet, pilots must complete the appropriate training program:</p>

<ul>
    <li><strong>Ground School:</strong> Complete aircraft systems training</li>
    <li><strong>Simulator Training:</strong> Demonstrate proficiency in normal and emergency procedures</li>
    <li><strong>Line Training:</strong> Complete supervised flights with qualified instructor</li>
    <li><strong>Proficiency Check:</strong> Pass comprehensive evaluation</li>
    <li><strong>Recurrent Training:</strong> Annual refresher training required</li>
</ul>

<div class="warning-box">
    <div class="box-title">
        <i class="fas fa-certificate"></i>
        Type Rating Validity
    </div>
    <p>Type ratings are valid for 12 months and require recurrent training for renewal. Flying without a current type rating is strictly prohibited.</p>
</div>

<h2>Airbus A320/A321 Family Procedures</h2>

<h3>Normal Operations</h3>

<h4>Engine Start Procedures</h4>
<div class="code-block">
A320/A321 Engine Start:
1. Beacon - ON
2. APU Bleed - ON (if APU available)
3. Engine Master 1 - ON
4. Engine Start 1 - START
5. Monitor N2, EGT, fuel flow
6. At stabilized idle, repeat for Engine 2
7. APU - OFF (when both engines stable)
</div>

