<h3>Short Runway Operations</h3>
<p>The ATR 72-600 excels at short runway operations common in Caribbean destinations:</p>

<h4>Short Field Takeoff</h4>
<ol>
    <li>Use maximum allowable takeoff power</li>
    <li>Rotate at calculated VR speed</li>
    <li>Maintain VY for best rate of climb</li>
    <li>Clean up configuration promptly</li>
    <li>Monitor engine parameters closely</li>
</ol>

<h4>Short Field Landing</h4>
<ul>
    <li>Plan for steeper approach if necessary</li>
    <li>Use maximum reverse thrust after touchdown</li>
    <li>Apply maximum braking as appropriate</li>
    <li>Consider overweight landing procedures if required</li>
</ul>

<h2>Emergency Procedures</h2>

<h3>Engine Failure Procedures</h3>
<div class="danger-box">
    <div class="box-title">
        <i class="fas fa-exclamation-triangle"></i>
        Engine Failure Response
    </div>
    <p>Immediate memory items must be executed without reference to checklists for critical emergencies.</p>
</div>

<h4>Engine Failure During Takeoff</h4>
<ol>
    <li><strong>Before V1:</strong> Abort takeoff, apply maximum braking</li>
    <li><strong>After V1:</strong> Continue takeoff, maintain directional control</li>
    <li><strong>After liftoff:</strong> Maintain V2, clean up configuration</li>
    <li><strong>Level off:</strong> Complete engine failure checklist</li>
    <li><strong>Landing:</strong> Plan single-engine approach and landing</li>
</ol>

<h3>Pressurization Emergency</h3>
<p>Rapid decompression requires immediate crew action:</p>
<ul>
    <li><strong>Oxygen Masks:</strong> Don immediately, establish communications</li>
    <li><strong>Emergency Descent:</strong> Initiate immediate descent to safe altitude</li>
    <li><strong>Crew Coordination:</strong> Divide responsibilities between crew members</li>
    <li><strong>Passenger Safety:</strong> Ensure passenger masks deployed and used</li>
    <li><strong>Diversion:</strong> Plan immediate diversion to nearest suitable airport</li>
</ul>

<h2>Maintenance Coordination</h2>

<h3>Pre-Flight Inspection</h3>
<p>Pilots are responsible for ensuring aircraft airworthiness before each flight:</p>

<h4>Documentation Review</h4>
<ul>
